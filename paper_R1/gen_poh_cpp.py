"""Generate src/PohSMC.h from the CellML encoding of Poh et al. 2012 (human jejunal SMC; PLoS One 7:e42385; models.cellml.org/e/105,
workspace yc_poh/poh_2012 @ 713cd294, file poh_2012.cellml) with Myokit (tested with 1.38.0).
The model's own ICC drive (component I_stim: Gcouple 2.6 nS to a prescribed ICC waveform) is replaced by an external current Iext
(pA, outward positive), which keeps its place in the membrane equation and in d[K]i/dt (carried by K+, as I_stim was).
Usage: <python with myokit> paper_R1/gen_poh_cpp.py <path to poh_2012.cellml>   (writes src/PohSMC.h)
"""
import os, sys, math
import myokit, myokit.formats

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
m = myokit.formats.importer("cellml").model(src)

stim = m.get("I_stim.I_stim")
iext = m.get("I_stim").add_variable("Iext")
iext.set_rhs(0)
iext.set_unit(stim.unit())
stim.set_rhs(myokit.Name(iext))
m.validate()

states = list(m.states())
idx = {s.qname(): i for i, s in enumerate(states)}
cname = lambda v: v.qname().replace(".", "__")

w = myokit.formats.ewriter("ansic")
def lhs(x):
    v = x.var()
    if isinstance(x, myokit.Derivative):
        return f"dy[{idx[v.qname()]}]"
    if v.is_state():
        return f"y[{idx[v.qname()]}]"
    if v.binding() == "time":
        return "0.0"
    if v.qname() == "I_stim.Iext":
        return "Iext"
    return cname(v)
w.set_lhs_function(lhs)

lines = []
order = m.solvable_order()
for comp, eqs in order.items():
    for eq in eqs:
        v = eq.lhs.var()
        if v.binding() == "time" or v.qname() == "I_stim.Iext":
            continue
        if isinstance(eq.lhs, myokit.Derivative):
            lines.append(f"\t\tdy[{idx[v.qname()]}] = {w.ex(eq.rhs)};")
        else:
            lines.append(f"\t\tconst double {cname(v)} = {w.ex(eq.rhs)};")

# diagonal of the Jacobian, b_i = -d f_i / d y_i, from fully expanded right-hand sides (Iext kept as a name), for the
# generalized Rush-Larsen step y_i += f_i (1 - exp(-b_i h)) / b_i (Sundnes et al. 2009); the BK and Na Markov states have rates
# up to ~2000 /ms, which explicit Euler cannot handle at practical step sizes.
diag = []
for i, st in enumerate(states):
    e = st.rhs().clone(expand=True, retain=[iext])
    d = e.diff(myokit.Name(st))
    diag.append(f"		b[{i}] = -({w.ex(d)});")

init = ", ".join(repr(s.initial_value(as_float=True)) for s in states)
names = "\n".join(f"//   y[{i}] {s.qname()}" for i, s in enumerate(states))
hdr = f'''// AUTO-GENERATED by paper_R1/gen_poh_cpp.py from poh_2012.cellml (Poh, Corrias, Cheng, Buist 2012 PLoS One 7:e42385,
// models.cellml.org/e/105). Do not edit by hand. I_stim replaced by the external current Iext (pA, outward positive, carried by K+).
// Interface mirrors SmoothM: Vm, Igap (pA, outward positive), delT (ms), Cm (pF), Integrate(). Generalized Rush-Larsen (GRL1) with sub-steps <= dtSub.
// States:
{names}
#pragma once
#include <cmath>
#include <algorithm>

class PohSMC
{{
public:
	static const int N = {len(states)};
	double y[N] = {{ {init} }};
	double Vm = y[0];
	double Igap = 0, Istim = 0, delT = 0.1, dtSub = 0.01;
	const double Cm = 50.0;
	void InitializeVar() {{ PohSMC fresh; std::copy(fresh.y, fresh.y + N, y); Vm = y[0]; Igap = Istim = 0; }}
	void Rhs(const double* y, double* dy, double Iext) const
	{{
{chr(10).join(lines)}
	}}
	void Diag(const double* y, double* b, double Iext) const
	{{
{chr(10).join(diag)}
	}}
	void Integrate(int = 0)
	{{
		y[0] = Vm;
		const int n = std::max(1, (int)std::ceil(delT / dtSub - 1e-9));
		const double h = delT / n;
		double dy[N], b[N];
		for (int k = 0; k < n; k++)
		{{
			Rhs(y, dy, Igap + Istim);
			Diag(y, b, Igap + Istim);
			for (int i = 0; i < N; i++) y[i] += dy[i] * (b[i] > 1e-12 ? -std::expm1(-b[i] * h) / b[i] : h);
		}}
		Vm = y[0];
	}}
}};
'''
assert idx["membrane.V"] == 0, "membrane.V must be state 0"
out = os.path.join(root, "src", "PohSMC.h")
open(out, "w", encoding="utf-8").write(hdr)
print("wrote", out, "states", len(states), "equations", len(lines))
